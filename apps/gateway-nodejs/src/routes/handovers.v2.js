const express = require('express');
const router = express.Router();
const { body, param, validationResult } = require('express-validator');
const fabricClient = require('../utils/fabricClient');
const logger = require('../utils/logger');
const { requireMSP, optionalMSP, requireHandoverReceiver } = require('../middleware/mspValidation');
const { generateHandoverRequestSignature, generateHandoverAcceptSignature, generateHandoverRejectSignature } = require('../utils/signatureHelper');

const CHANNEL_NAME = process.env.CHANNEL_NAME || 'supplychain-channel';
const CHAINCODE_NAME = process.env.CHAINCODE_NAME || 'supplychain_cc';

// Validation middleware
const validate = (req, res, next) => {
    const errors = validationResult(req);
    if (!errors.isEmpty()) {
        return res.status(400).json({
            success: false,
            errors: errors.array()
        });
    }
    next();
};

/**
 * @route   POST /api/v2/handovers/manufacturer-shipper
 * @desc    Request handover from Manufacturer to Shipper (AUTO-GENERATES SIGNATURE)
 * @access  Private (Manufacturer MSP only)
 * @workflow Step 1 of 2-party approval
 * @security MSP validation enforced - only OrgManufacturerMSP allowed
 * @body {string} productId - Product ID
 * @body {string} shipperId - Shipper ID
 * @body {string} waybill - Waybill number
 * @note Signature is auto-generated by backend, no need to send from UI
 */
router.post('/manufacturer-shipper',
    requireMSP('manufacturer'),
    [
        body('productId').notEmpty().withMessage('Product ID is required'),
        body('shipperId').notEmpty().withMessage('Shipper ID is required'),
        body('waybill').notEmpty().withMessage('Waybill is required')
    ],
    validate,
    async (req, res) => {
        try {
            const { productId, shipperId, waybill } = req.body;
            const userIdentity = req.headers['x-user-identity'];
            const [org, userId] = userIdentity.split(':');

            logger.info(`[Handover] Manufacturer requesting handover to shipper for product ${productId}`);

            // AUTO-GENERATE SIGNATURE (no need for UI to provide)
            const signature = await generateHandoverRequestSignature(org, userId, productId, 'shipper');
            logger.info(`[Handover] Auto-generated signature: ${signature.length} chars`);

            // Submit transaction to blockchain
            await fabricClient.submitTransaction(
                CHANNEL_NAME,
                CHAINCODE_NAME,
                'RequestHandoverToShipper',
                productId,
                shipperId,
                waybill,
                signature
            );

            // Query the product to get the actual handover ID (includes TxID suffix)
            // Product.pendingHandover is updated with the real handover ID
            await new Promise(resolve => setTimeout(resolve, 500));

            const productResult = await fabricClient.evaluateTransaction(
                CHANNEL_NAME,
                CHAINCODE_NAME,
                'GetProduct',
                productId
            );

            const product = productResult ? JSON.parse(productResult.toString()) : null;
            const handoverId = product && product.pendingHandover ?
                product.pendingHandover :
                `HANDOVER-${productId}-SHIPPER`;

            logger.info(`[Handover] Created: ${handoverId}`);

            res.status(201).json({
                success: true,
                message: 'Handover request created successfully',
                data: {
                    handoverId,
                    productId,
                    fromOrg: 'Manufacturer',
                    toOrg: 'Shipper',
                    status: 'PENDING',
                    metadata: {
                        shipperId,
                        waybill
                    }
                }
            });

        } catch (error) {
            logger.error('[Handover] Error requesting manufacturer-shipper handover:', error);

            // Parse specific errors
            if (error.message.includes('unauthorized')) {
                return res.status(403).json({
                    success: false,
                    error: 'Unauthorized: Only manufacturer can request this handover'
                });
            }
            if (error.message.includes('already has pending handover')) {
                return res.status(409).json({
                    success: false,
                    error: 'Product already has a pending handover'
                });
            }
            if (error.message.includes('must be in Manufactured state')) {
                return res.status(400).json({
                    success: false,
                    error: 'Product must be in Manufactured state'
                });
            }

            res.status(500).json({
                success: false,
                error: error.message
            });
        }
    }
);

