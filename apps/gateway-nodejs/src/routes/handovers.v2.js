/**
 * @route   GET /api/v2/handovers/pending
 * @desc    Get pending handovers for current organization
 * @access  Private (All MSPs - filtered by caller's MSP)
 * @security Optional MSP validation (chaincode filters by MSP)
 */
router.get('/pending', optionalMSP, async (req, res) => {
    try {
        logger.info('[Handover] Fetching pending handovers for organization');

        // Query blockchain
        const result = await fabricClient.evaluateTransaction(
            CHANNEL_NAME,
            CHAINCODE_NAME,
            'GetPendingHandoversForOrg'
        );

        const resultStr = result ? result.toString() : '';
        const handovers = resultStr && resultStr.trim() !== '' ? JSON.parse(resultStr) : [];

        logger.info(`[Handover] Found ${handovers.length} pending handovers`);

        res.status(200).json({
            success: true,
            count: handovers.length,
            data: handovers
        });

    } catch (error) {
        logger.error('[Handover] Error fetching pending handovers:', error);
        res.status(500).json({
            success: false,
            error: error.message
        });
    }
});

/**
 * @route   GET /api/v2/handovers/:id
 * @desc    Get handover details by ID
 * @access  Private (All MSPs)
 * @security Optional MSP validation (logs identity)
 */
router.get('/:id',
    optionalMSP,
    param('id').notEmpty().withMessage('Handover ID is required'),
    validate,
    async (req, res) => {
        try {
            const { id } = req.params;

            logger.info(`[Handover] Fetching handover details: ${id}`);

            // Query blockchain
            const result = await fabricClient.evaluateTransaction(
                CHANNEL_NAME,
                CHAINCODE_NAME,
                'GetHandover',
                id
            );

            const resultStr = result ? result.toString() : '';
            const handover = resultStr && resultStr.trim() !== '' ? JSON.parse(resultStr) : null;

            if (!handover) {
                return res.status(404).json({
                    success: false,
                    error: 'Handover not found'
                });
            }

            res.status(200).json({
                success: true,
                data: handover
            });

        } catch (error) {
            logger.error(`[Handover] Error fetching handover ${req.params.id}:`, error);

            if (error.message.includes('does not exist')) {
                return res.status(404).json({
                    success: false,
                    error: 'Handover not found'
                });
            }

            res.status(500).json({
                success: false,
                error: error.message
            });
        }
    }
);

