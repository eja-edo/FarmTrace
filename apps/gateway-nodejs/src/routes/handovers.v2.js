/**
 * @route   POST /api/v2/handovers/:id/accept
 * @desc    Accept handover (AUTO-GENERATES NONCE-BASED SIGNATURE)
 * @access  Private (ToOrg MSP: Shipper, Warehouse, or Retailer)
 * @workflow Step 2 of 2-party approval
 * @security Dynamic MSP validation - only handover recipient can accept
 * @body {string} receiverId - ID of person/entity receiving (e.g., DRIVER-001)
 * @note Fetches nonce from blockchain and auto-generates signature
 */
router.post('/:id/accept',
    requireHandoverReceiver,
    [
        param('id').notEmpty().withMessage('Handover ID is required'),
        body('receiverId').notEmpty().withMessage('Receiver ID is required')
    ],
    validate,
    async (req, res) => {
        try {
            const { id } = req.params;
            const { receiverId } = req.body;
            const userIdentity = req.headers['x-user-identity'];
            const [org, userId] = userIdentity.split(':');

            logger.info(`[Handover] Accepting handover: ${id}`);

            // STEP 1: Get handover details to extract nonce
            const handoverResult = await fabricClient.evaluateTransaction(
                CHANNEL_NAME,
                CHAINCODE_NAME,
                'GetHandover',
                id
            );

            const handover = handoverResult ? JSON.parse(handoverResult.toString()) : null;
            if (!handover || !handover.nonce) {
                return res.status(404).json({
                    success: false,
                    error: 'Handover not found or missing nonce'
                });
            }

            logger.info(`[Handover] Retrieved nonce: ${handover.nonce.substring(0, 40)}...`);

            // STEP 2: AUTO-GENERATE SIGNATURE with nonce
            const signature = await generateHandoverAcceptSignature(org, userId, id, handover.nonce, receiverId);
            logger.info(`[Handover] Auto-generated acceptance signature: ${signature.length} chars`);

            // Submit transaction to blockchain
            await fabricClient.submitTransaction(
                CHANNEL_NAME,
                CHAINCODE_NAME,
                'AcceptHandover',
                id,
                receiverId,
                signature
            );

            logger.info(`[Handover] Accepted: ${id}`);

            res.status(200).json({
                success: true,
                message: 'Handover accepted successfully',
                data: {
                    handoverId: id,
                    status: 'ACCEPTED',
                    acceptedAt: new Date().toISOString()
                }
            });

        } catch (error) {
            logger.error(`[Handover] Error accepting handover ${req.params.id}:`, error);

            // Parse specific errors
            if (error.message.includes('unauthorized') || error.message.includes('cannot accept')) {
                return res.status(403).json({
                    success: false,
                    error: 'Unauthorized: You cannot accept this handover'
                });
            }
            if (error.message.includes('not in pending state')) {
                return res.status(409).json({
                    success: false,
                    error: 'Handover is not in pending state'
                });
            }
            if (error.message.includes('does not exist')) {
                return res.status(404).json({
                    success: false,
                    error: 'Handover not found'
                });
            }

            res.status(500).json({
                success: false,
                error: error.message
            });
        }
    }
);

